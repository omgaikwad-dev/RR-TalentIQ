"""
RR TalentIQ - Player Auction Valuation Engine
Estimates empirical auction price bands, role-scarcity multipliers,
and maximum recommended bid ceilings for uncapped domestic cricketers.
"""

from typing import Dict, Any, Optional
import pandas as pd
import numpy as np


# Uncapped Player Official Base Price Tiers (₹ Lakhs)
STANDARD_UNCAPPED_BASE_PRICE_LAKHS = 30.0

# Role Scarcity Multipliers in IPL Mega & Mini Auctions
# Derived from historical bidding premiums for specialized domestic skillsets
ROLE_SCARCITY_FACTORS = {
    "Pace Bowler": 1.40,           # Extreme demand for Indian fast bowlers (140+ kph)
    "Bowling All-Rounder": 1.45,   # Genuine lower-order pace/spin all-rounders
    "Batting All-Rounder": 1.35,   # Top-order batters who roll their arm over
    "Finisher": 1.35,              # High-strike-rate death-overs hitters
    "Spin Bowler": 1.25,           # Mystery wrist-spin & restrictive finger spin
    "Wicketkeeper-Batter": 1.20,   # Dynamic keepers
    "Top-order Batter": 1.15,      # High volume of domestic opening options
    "Middle-order Batter": 1.20
}


class PlayerValuationEngine:
    """
    Computes fair estimated market value (EMV) and recommended bidding ceilings.
    
    DISCLAIMER:
    All auction valuations generated by this engine are statistical estimates
    derived from role scarcity, age curves, and domestic performance metrics.
    They do not represent guaranteed market clearing prices.
    """

    @classmethod
    def estimate_player_valuation(
        cls,
        player_row: Dict[str, Any],
        base_price_lakhs: float = STANDARD_UNCAPPED_BASE_PRICE_LAKHS
    ) -> Dict[str, Any]:
        """
        Calculates estimated market value (EMV) and max safe bid threshold.
        """
        role = str(player_row.get("playing_role", "Top-order Batter"))
        age = float(player_row.get("age", 25.0) or 25.0)
        oss = float(player_row.get("overall_scouting_score", 50.0) or 50.0)
        squad_fit = float(player_row.get("squad_fit_score", 60.0) or 60.0)

        # 1. Role Scarcity Multiplier
        scarcity = ROLE_SCARCITY_FACTORS.get(role, 1.20)

        # 2. Performance Multiplier based on Overall Scouting Score (OSS 0-100)
        # Baseline score of 50 -> 1.0x; 75 -> 2.5x; 90+ -> 4.5x
        perf_factor = max(1.0, 1.0 + ((oss - 50.0) / 10.0) * 0.85)

        # 3. Age Premium Factor (Under 22 assets attract furious bidding wars)
        if age < 21.0:
            age_factor = 1.35
        elif age < 23.5:
            age_factor = 1.22
        elif age < 26.0:
            age_factor = 1.10
        else:
            age_factor = 1.00

        # 4. Squad Fit Premium
        fit_factor = 1.0 + ((squad_fit - 60.0) / 100.0) * 0.25

        # 5. Estimated Market Value (EMV)
        # Scaled in Lakhs
        raw_emv = base_price_lakhs * perf_factor * scarcity * age_factor * fit_factor
        estimated_market_value = round(raw_emv, 1)

        # 6. Upper Bidding Ceiling (Beyond which the player represents negative ROI / overspend)
        max_recommended_bid = round(estimated_market_value * 1.40, 1)

        # Valuation Tier Classification
        if estimated_market_value >= 200.0:
            val_tier = "Tier 1: High-Bidding War Target (₹2.0 Cr+)"
            risk_profile = "High Stake Investment"
        elif estimated_market_value >= 100.0:
            val_tier = "Tier 2: Prime Mid-Tier Prospect (₹1.0 Cr – ₹2.0 Cr)"
            risk_profile = "Balanced ROI"
        elif estimated_market_value >= 50.0:
            val_tier = "Tier 3: Smart Value Pick (₹50 L – ₹1.0 Cr)"
            risk_profile = "High ROI Potential"
        else:
            val_tier = "Tier 4: Base Price Value Steal (₹30 L – ₹50 L)"
            risk_profile = "Low Risk Reserve"

        return {
            "player_name": player_row.get("player_name", "Unknown"),
            "base_price_lakhs": base_price_lakhs,
            "estimated_market_value_lakhs": estimated_market_value,
            "max_recommended_bid_lakhs": max_recommended_bid,
            "valuation_tier": val_tier,
            "risk_profile": risk_profile,
            "role_scarcity_multiplier": round(scarcity, 2),
            "age_premium_multiplier": round(age_factor, 2),
            "is_unverified_estimate": True
        }

    @classmethod
    def attach_valuations_to_dataset(cls, df: pd.DataFrame) -> pd.DataFrame:
        """
        Attaches valuation fields to an entire player dataframe.
        """
        v_df = df.copy()
        emvs = []
        max_bids = []
        tiers = []

        for _, row in v_df.iterrows():
            res = cls.estimate_player_valuation(row.to_dict())
            emvs.append(res["estimated_market_value_lakhs"])
            max_bids.append(res["max_recommended_bid_lakhs"])
            tiers.append(res["valuation_tier"])

        v_df["estimated_market_value_lakhs"] = emvs
        v_df["max_recommended_bid_lakhs"] = max_bids
        v_df["valuation_tier"] = tiers
        return v_df

